import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {importCSV,mergeRows,shift} from '../analytics.mjs';
const [kind,start,end,dailyFile,postFile,notesFile,acquiredAt]=process.argv.slice(2);
if(!['weekly','monthly'].includes(kind)||![start,end].every(v=>/^\d{4}-\d{2}-\d{2}$/.test(v||''))||start>end||!acquiredAt||!Number.isFinite(Date.parse(acquiredAt)))throw Error('Usage: node scripts/publish-report.mjs weekly|monthly START END DAILY.csv POSTS.csv NOTES.json ACQUIRED_AT_ISO');
const daily=importCSV(fs.readFileSync(dailyFile,'utf8')), posts=importCSV(fs.readFileSync(postFile,'utf8'));
if(daily.type!=='daily'||posts.type!=='post')throw Error('Wrong CSV types');
const selected=x=>mergeRows([],x).filter(r=>r.date>=start&&r.date<=end);
const days=selected(daily.data), rows=selected(posts.data);
if(!days.length)throw Error('No daily rows in target period');
const expectedDays=Math.round((Date.parse(end)-Date.parse(start))/86400000)+1;
const acquiredDay=new Date(Date.parse(acquiredAt)+9*3600000).toISOString().slice(0,10);
const keys=['impressions','engagements','bookmarks','follows','unfollows','profile','likes','replies','reposts'];
const sum=rs=>Object.fromEntries(keys.map(k=>[k,rs.length&&rs.every(r=>r[k]!=null)?rs.reduce((n,r)=>n+r[k],0):null]));
const totals=sum(days);
const priorEnd=shift(start,-1);
const priorStart=kind==='monthly'?priorEnd.slice(0,7)+'-01':shift(start,-expectedDays);
const priorRows=mergeRows([],daily.data).filter(r=>r.date>=priorStart&&r.date<=priorEnd);
const priorExpected=Math.round((Date.parse(priorEnd)-Date.parse(priorStart))/86400000)+1;
const previous=priorRows.length===priorExpected?{start:priorStart,end:priorEnd,days:priorExpected,totals:sum(priorRows)}:null;
const dailySeries=Array.from({length:expectedDays},(_,i)=>{const date=shift(start,i),r=days.find(r=>r.date===date);return {date,...Object.fromEntries(keys.map(k=>[k,r?.[k]??null]))};});

const inputNotes=JSON.parse(fs.readFileSync(notesFile,'utf8'));
const notes=Array.isArray(inputNotes)?inputNotes:inputNotes.notes;
const nextAction=typeof inputNotes.nextAction==='string'?inputNotes.nextAction:'上位投稿の型を1本再現し、保存とフォローで検証する。';
if(!Array.isArray(notes)||!notes.every(n=>typeof n==='string'))throw Error('Notes must be string[]');
const id=`${kind}-${start}`;
const result={id,kind,account:'muku_sns',start,end,acquiredAt,days:days.length,expectedDays,provisional:end>=acquiredDay||days.length!==expectedDays,totals,previous,dailySeries,nextAction,notes,postCount:rows.length,topPosts:rows.sort((a,b)=>(b.bookmarks??-1)-(a.bookmarks??-1)).slice(0,5).map(r=>({date:r.date,text:r.text.slice(0,220),url:r.url,impressions:r.impressions,bookmarks:r.bookmarks,follows:r.follows}))};
const dir=fileURLToPath(new URL('../reports/',import.meta.url));fs.mkdirSync(dir,{recursive:true});
const manifestPath=path.join(dir,'index.json');
let manifest=fs.existsSync(manifestPath)?JSON.parse(fs.readFileSync(manifestPath,'utf8')):[];
manifest=manifest.filter(r=>r.id!==id);manifest.push({id,kind,start,end,provisional:result.provisional});manifest.sort((a,b)=>b.start.localeCompare(a.start));
fs.writeFileSync(path.join(dir,id+'.json'),JSON.stringify(result,null,2)+'\n');fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({id,days:days.length,postCount:rows.length,provisional:result.provisional}));
