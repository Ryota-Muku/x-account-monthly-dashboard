import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
test('monthly publisher keeps interim status, equal-day baseline, history and rolls back invalid sources',()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'x-publisher-test-'));
 const repo=fileURLToPath(new URL('../',import.meta.url));
 fs.mkdirSync(path.join(root,'scripts'));fs.mkdirSync(path.join(root,'reports'));
 fs.copyFileSync(path.join(repo,'accounts.mjs'),path.join(root,'accounts.mjs'));
 fs.copyFileSync(path.join(repo,'analytics.mjs'),path.join(root,'analytics.mjs'));
 fs.copyFileSync(path.join(repo,'scripts/publish-report.mjs'),path.join(root,'scripts/publish-report.mjs'));
 const existing=[{id:'weekly-2026-10-19',kind:'weekly',start:'2026-10-19',end:'2026-10-25'}];
 fs.writeFileSync(path.join(root,'reports/index.json'),JSON.stringify(existing));
 const lines=['Date,Impressions,Engagements,Bookmarks,Follows'];
 for(let d=1;d<=31;d++)lines.push(`2026-10-${String(d).padStart(2,'0')},100,10,5,1`);
 for(let d=1;d<=22;d++)lines.push(`2026-11-${String(d).padStart(2,'0')},200,10,5,1`);
 fs.writeFileSync(path.join(root,'daily.csv'),lines.join('\n'));
 fs.writeFileSync(path.join(root,'posts.csv'),'Post id,Post text,Time,Impressions,Bookmarks\n2122333333333333333,fixture,2026-11-16,100,2');
 const notes={notes:['synthetic fixture'],insights:{observations:[],hypotheses:[],experiments:[]}};
 fs.writeFileSync(path.join(root,'notes.json'),JSON.stringify(notes));
 const args=[path.join(root,'scripts/publish-report.mjs'),'monthly','2026-11-01','2026-11-22',path.join(root,'daily.csv'),path.join(root,'posts.csv'),path.join(root,'notes.json'),'2026-11-23T03:00:00Z'];
 execFileSync(process.execPath,args);
 const reportFile=path.join(root,'reports/monthly-2026-11-01.json');
 const before=fs.readFileSync(reportFile,'utf8'),report=JSON.parse(before);
 assert.equal(report.provisional,true);assert.equal(report.days,22);assert.equal(report.calendarExpectedDays,30);
 assert.equal(report.matchedComparison.end,'2026-10-22');assert.equal(report.matchedComparison.totals.impressions,2200);
 assert.equal(report.previous.totals.impressions,3100);assert.equal(report.totals.impressions,4400);
 assert.ok(JSON.parse(fs.readFileSync(path.join(root,'reports/index.json'))).some(r=>r.id===existing[0].id));
 notes.competitorResearch={examples:[{url:'javascript:alert(1)',date:'2026-11-20',summary:'bad',observedAt:'2026-11-23T03:00:00Z'}]};
 fs.writeFileSync(path.join(root,'notes.json'),JSON.stringify(notes));
 assert.throws(()=>execFileSync(process.execPath,args,{stdio:'pipe'}));assert.equal(fs.readFileSync(reportFile,'utf8'),before);
});
